const DICTS: Record<Language, Dict> = { en, es };

export function dictFor(language: string | undefined): Dict {
  return DICTS[(language as Language) ?? "en"] ?? en;
}

export function dateLocaleFor(language: string | undefined): string {
  return LANGUAGES.find((l) => l.id === (language as Language))?.dateLocale ?? "en-US";
}

/** Replace {placeholders} in a translation string. */
export function interpolate(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}
